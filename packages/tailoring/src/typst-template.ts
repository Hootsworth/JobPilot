import type { CoverLetterContent, IndiaProfile, JsonResume, ResumeTemplateId } from '@jobpilot/shared';

export function escapeTypst(text: string): string {
  return text
    .replace(/\\/g, '\\\\')
    .replace(/([#$@*_<>[\]~`])/g, '\\$1');
}

export function generateTypstResumeSource(
  resume: JsonResume,
  indiaProfile?: IndiaProfile,
  templateId: ResumeTemplateId = 'ats-classic'
): string {
  const isCompact = templateId === 'ats-compact';
  const isExecutive = templateId === 'ats-executive';
  const isDetailed = templateId === 'ats-detailed';
  const margin = isCompact ? '0.45in' : isExecutive ? '0.68in' : isDetailed ? '0.52in' : '0.6in';
  const fontSize = isCompact ? '9.5pt' : isExecutive ? '10.5pt' : '10pt';
  const fontStack = isExecutive
    ? '("Liberation Serif", "Georgia", "Times New Roman")'
    : '("Liberation Sans", "DejaVu Sans", "Arial")';
  const ruleStroke = isExecutive ? '0.9pt + rgb("#1a1a1a")' : '0.6pt + rgb("#333333")';

  const lines: string[] = [
    `// Auto-generated by JobPilot (${templateId} ATS-safe single-column layout)`,
    isDetailed
      ? `#set page(paper: "a4", margin: (x: ${margin}, y: ${margin}), numbering: "1 / 1", number-align: right)`
      : `#set page(paper: "a4", margin: (x: ${margin}, y: ${margin}))`,
    `#set text(font: ${fontStack}, size: ${fontSize}, fill: rgb("#111111"))`,
    '#set par(leading: 0.55em, justify: false)',
    '',
    '#let section_heading(title) = {',
    '  v(7pt)',
    '  text(size: 10.5pt, weight: "bold", upper(title))',
    '  v(-4pt)',
    `  line(length: 100%, stroke: ${ruleStroke})`,
    '  v(3pt)',
    '}',
    ''
  ];

  const name = escapeTypst(resume.basics.name || 'Candidate Name');
  lines.push(`#align(center)[#text(size: ${isExecutive ? '17pt' : '16pt'}, weight: "bold")[${name}]]`);
  if (resume.basics.label) {
    lines.push(`#align(center)[#text(size: 10pt, fill: rgb("#444444"))[${escapeTypst(resume.basics.label)}]]`);
  }

  const contactParts = [
    resume.basics.email,
    resume.basics.phone,
    resume.basics.location?.city
      ? [resume.basics.location.city, resume.basics.location.countryCode].filter(Boolean).join(', ')
      : '',
    resume.basics.url,
    ...(resume.basics.profiles ?? []).map((p) => p.url || `${p.network}: ${p.username}`)
  ]
    .filter((s): s is string => Boolean(s && s.trim()))
    .map(escapeTypst);

  if (contactParts.length > 0) {
    lines.push(`#align(center)[#text(size: 9pt)[${contactParts.join(' | ')}]]`);
  }

  if (resume.basics.summary?.trim()) {
    lines.push('');
    lines.push('#section_heading("Summary")');
    lines.push(escapeTypst(resume.basics.summary.trim()));
  }

  if (resume.skills.length > 0) {
    lines.push('');
    lines.push('#section_heading("Technical Skills")');
    for (const grp of resume.skills) {
      if (grp.keywords.length === 0) continue;
      lines.push(`*${escapeTypst(grp.name)}:* ${escapeTypst(grp.keywords.join(', '))} \\`);
    }
  }

  if (resume.work.length > 0) {
    lines.push('');
    lines.push('#section_heading("Experience")');
    for (const w of resume.work) {
      const dates = [w.startDate, w.endDate || 'Present'].filter(Boolean).join(' – ');
      lines.push(
        `*${escapeTypst(w.position)}* — ${escapeTypst(w.name)}${w.location ? ` (${escapeTypst(w.location)})` : ''} #h(1fr) _${escapeTypst(dates)}_ \\`
      );
      if (w.summary?.trim()) {
        lines.push(`${escapeTypst(w.summary.trim())} \\`);
      }
      for (const h of w.highlights) {
        lines.push(`- ${escapeTypst(h)}`);
      }
      lines.push('#v(3pt)');
    }
  }

  if (resume.projects.length > 0) {
    lines.push('');
    lines.push('#section_heading("Projects")');
    for (const p of resume.projects) {
      const stack = (p.keywords ?? []).length > 0 ? ` (${p.keywords!.join(', ')})` : '';
      lines.push(`*${escapeTypst(p.name)}*${escapeTypst(stack)}${p.url ? ` — ${escapeTypst(p.url)}` : ''} \\`);
      if (p.description?.trim()) {
        lines.push(`${escapeTypst(p.description.trim())} \\`);
      }
      for (const h of p.highlights) {
        lines.push(`- ${escapeTypst(h)}`);
      }
      lines.push('#v(3pt)');
    }
  }

  if (resume.education.length > 0) {
    lines.push('');
    lines.push('#section_heading("Education")');
    for (const e of resume.education) {
      const dates = [e.startDate, e.endDate].filter(Boolean).join(' – ');
      const deg = [e.studyType, e.area].filter(Boolean).join(' in ');
      const score = e.score ? ` · Score: ${e.score}` : '';
      lines.push(
        `*${escapeTypst(e.institution)}*${deg ? ` — ${escapeTypst(deg)}` : ''}${escapeTypst(score)} #h(1fr) _${escapeTypst(dates)}_ \\`
      );
      if (isDetailed && e.courses && e.courses.length > 0) {
        lines.push(`_Relevant Coursework:_ ${escapeTypst(e.courses.join(', '))} \\`);
      }
    }
    if (indiaProfile?.tenthPercentage != null || indiaProfile?.twelfthPercentage != null) {
      const boardParts = [
        indiaProfile.twelfthPercentage != null ? `Class XII: ${indiaProfile.twelfthPercentage}%` : '',
        indiaProfile.tenthPercentage != null ? `Class X: ${indiaProfile.tenthPercentage}%` : ''
      ].filter(Boolean);
      if (boardParts.length > 0) {
        lines.push(escapeTypst(boardParts.join(' | ')));
      }
    }
  }

  if (isDetailed) {
    if (resume.certificates.length > 0) {
      lines.push('');
      lines.push('#section_heading("Certifications")');
      for (const c of resume.certificates) {
        lines.push(
          `- *${escapeTypst(c.name)}*${c.issuer ? ` (${escapeTypst(c.issuer)})` : ''}${c.date ? ` — ${escapeTypst(c.date)}` : ''}`
        );
      }
    }
    if (resume.awards.length > 0) {
      lines.push('');
      lines.push('#section_heading("Honors & Awards")');
      for (const a of resume.awards) {
        lines.push(
          `- *${escapeTypst(a.title)}*${a.awarder ? ` — ${escapeTypst(a.awarder)}` : ''}${a.date ? ` (${escapeTypst(a.date)})` : ''}${a.summary ? `: ${escapeTypst(a.summary)}` : ''}`
        );
      }
    }
    if (resume.publications.length > 0) {
      lines.push('');
      lines.push('#section_heading("Publications")');
      for (const pub of resume.publications) {
        lines.push(
          `- *${escapeTypst(pub.name)}*${pub.publisher ? ` — ${escapeTypst(pub.publisher)}` : ''}${pub.releaseDate ? ` (${escapeTypst(pub.releaseDate)})` : ''}`
        );
      }
    }
    if (resume.languages.length > 0) {
      lines.push('');
      lines.push('#section_heading("Languages")');
      lines.push(
        escapeTypst(
          resume.languages
            .map((l) => (l.fluency ? `${l.language} (${l.fluency})` : l.language))
            .join(' | ')
        )
      );
    }
  }

  return `${lines.join('\n')}\n`;
}

export function generateTypstCoverLetterSource(params: {
  basics: JsonResume['basics'];
  companyName: string;
  roleTitle: string;
  dateLabel?: string;
  content: CoverLetterContent;
}): string {
  const { basics, companyName, roleTitle, content } = params;
  const dateLabel =
    params.dateLabel ||
    new Date().toLocaleDateString('en-US', { year: 'numeric', month: 'long', day: 'numeric' });
  const contactParts = [
    basics.email,
    basics.phone,
    basics.location?.city
      ? [basics.location.city, basics.location.countryCode].filter(Boolean).join(', ')
      : '',
    basics.url
  ]
    .filter((v): v is string => Boolean(v && v.trim()))
    .map(escapeTypst);

  const lines: string[] = [
    '// Auto-generated by JobPilot (ATS-safe grounded cover letter)',
    '#set page(paper: "a4", margin: (x: 0.75in, y: 0.72in))',
    '#set text(font: ("Liberation Sans", "DejaVu Sans", "Arial"), size: 10.5pt, fill: rgb("#111111"))',
    '#set par(leading: 0.65em, justify: false)',
    '',
    `#text(size: 15pt, weight: "bold")[${escapeTypst(basics.name || 'Candidate Name')}]`,
    ...(basics.label
      ? [`\\ #text(size: 10pt, fill: rgb("#444444"))[${escapeTypst(basics.label)}]`]
      : []),
    ...(contactParts.length > 0
      ? [`\\ #text(size: 9pt, fill: rgb("#444444"))[${contactParts.join('  |  ')}]`]
      : []),
    '#v(6pt)',
    '#line(length: 100%, stroke: 0.6pt + rgb("#333333"))',
    '#v(10pt)',
    `${escapeTypst(dateLabel)} \\`,
    `*Re: Application for ${escapeTypst(roleTitle)}${companyName ? ` — ${escapeTypst(companyName)}` : ''}*`,
    '#v(10pt)',
    `${escapeTypst(content.salutation)}`,
    '#v(6pt)',
    escapeTypst(content.openingHook),
    '#v(6pt)'
  ];

  for (const para of content.bodyParagraphs) {
    if (!para.trim()) continue;
    lines.push(escapeTypst(para.trim()));
    lines.push('#v(6pt)');
  }

  lines.push(escapeTypst(content.closing));
  lines.push('#v(10pt)');
  lines.push(`Sincerely, \\`);
  lines.push(`*${escapeTypst(content.signature || basics.name || 'Candidate')}*`);

  return `${lines.join('\n')}\n`;
}
